export function knownProductionErrorMessage(detail) {
  if (typeof detail !== "string") return null;
  if (Object.hasOwn(knownErrors, detail)) return knownErrors[detail];
  const unrelated = /^Operation (\d+) does not belong to production order (\d+)$/.exec(detail);
  if (unrelated) return "A operação " + unrelated[1] + " não pertence à ordem de produção " + unrelated[2] + ".";
  const conflict = /^Scheduling conflict with (\d+) existing operation\(s\)$/.exec(detail);
  if (conflict) return "Conflito com " + conflict[1] + " operação(ões) já agendada(s).";
  const maintenance = /^Overlaps maintenance window (\d{4})-(\d{2})-(\d{2}) (\d{2}:\d{2})–(\d{2}:\d{2}) UTC(?: \((.*)\))?$/.exec(detail);
  if (maintenance) return "O horário coincide com uma janela de manutenção em " + maintenance[3] + "/" + maintenance[2] + "/" + maintenance[1] + ", das " + maintenance[4] + " às " + maintenance[5] + " (UTC)." + (maintenance[6] ? " Motivo: " + maintenance[6] : "");
  const successor = /^Moving this operation would violate (\d+) successor operation\(s\) that are already scheduled$/.exec(detail);
  if (successor) return "A alteração entra em conflito com " + successor[1] + " operação(ões) seguinte(s) já agendada(s).";
  const sequence = /^Operation (\d+) \((.+)\) must be scheduled before operation (\d+)$/.exec(detail);
  if (sequence) return "Agende a operação " + sequence[1] + " (" + sequence[2] + ") antes da operação " + sequence[3] + ".";
  const previous = /^Operation (\d+) \((.+)\) must finish before this operation can start$/.exec(detail);
  if (previous) return "A operação " + previous[1] + " (" + previous[2] + ") precisa terminar antes desta.";
  const enclosure = /^(.+) requires enclosure but (.+) does not have one$/.exec(detail);
  if (enclosure) return enclosure[1] + " exige uma câmara fechada. O recurso " + enclosure[2].replace("(unknown model)", "(modelo desconhecido)") + " não tem uma.";
  const state = /^Operation (\d+) has status '[^']+'; only pending\/queued operations can be (rescheduled|unscheduled)$/.exec(detail);
  if (state) return "A operação " + state[1] + " precisa estar pendente ou na fila para " + (state[2] === "rescheduled" ? "ser reagendada." : "ter o agendamento removido.");
  return null;
}

export function productionRequestMessage(error, fallback) {
  const detail = typeof error?.detail === "string" ? error.detail
    : typeof error?.payload?.detail === "string" ? error.payload.detail
      : error?.message;
  const known = knownProductionErrorMessage(detail);
  if (known) return known;
  const plan = /^Inspection does not satisfy plan ([^:]+):/.exec(detail || "");
  if (plan) return "A inspeção não atende ao plano " + plan[1] + ". Confira as medições e os critérios de aceitação.";
  const split = /^Split quantities must total the ordered quantity \(?(\d+(?:\.\d+)?)\)?/i.exec(detail || "");
  if (split) return "A soma das divisões precisa ser igual à quantidade solicitada: " + split[1] + " un.";
  return fallback;
}

